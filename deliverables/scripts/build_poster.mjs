import { chromium } from '/home/sujith/Documents/SIS-Karpathy-Map/sis-app/frontend/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
const root='/home/sujith/Documents/SIS-Karpathy-Map/deliverables';
const html=path.join(root,'poster-redesign.html');
const pdf=path.join(root,'SIS-System-Design-Poster.pdf');
const preview=path.join(root,'poster-redesign-preview.png');
if(!fs.existsSync(html)) throw new Error('Missing editable poster source: '+html);
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1680,height:1188},deviceScaleFactor:1});
await page.goto('file://'+html,{waitUntil:'load'});
await page.evaluate(()=>document.fonts.ready);
const images=await page.locator('img').evaluateAll(xs=>xs.map(i=>({src:i.getAttribute('src'),loaded:i.complete&&i.naturalWidth>0})));
const missing=images.filter(i=>!i.loaded);
if(missing.length) throw new Error('Missing poster images: '+JSON.stringify(missing));
const qa=await page.evaluate(()=>({panels:[...document.querySelectorAll('.panel')].map(p=>({heading:p.querySelector('h2')?.innerText,overflow:p.scrollHeight>p.clientHeight+2,scroll:p.scrollHeight,client:p.clientHeight})),sheet:document.querySelector('.sheet').getBoundingClientRect().toJSON(),pages:document.body.scrollHeight}));
await page.screenshot({path:preview,fullPage:true});
await page.pdf({path:pdf,format:'A3',landscape:true,printBackground:true,preferCSSPageSize:true});
await browser.close();
console.log(JSON.stringify({pdf,preview,images,qa},null,2));
if(qa.panels.some(p=>p.overflow)) process.exitCode=2;
