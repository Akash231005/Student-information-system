#!/usr/bin/env bash
# One command to bring the whole demo up: preflight, stack, data, API, health.
#
#   ./run.sh                start everything the demo needs
#   ./run.sh --with-tests   also run the test suite (drops and recreates tables, so it runs
#                           before seeding - the suite would otherwise wipe the demo data)
#   ./run.sh --verify       also run scripts/verify_stack.py (live crawl, ~1 minute)
#   ./run.sh --no-install   fail instead of installing uv
#   ./run.sh --stop         shorthand for ./stop.sh
#
# What it will not do: install system packages. Podman needs root, so this script prints the
# exact command for your distro instead of pretending to handle it.
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
APP="$ROOT/sis-app"
RUN="$APP/.run"
API_HOST=127.0.0.1
API_PORT=${API_PORT:-8000}
STORE_PORTS="5432 6379 27017 27019 27021 27022"
CONTAINERS="sis-postgres sis-redis sis-mongo-cfg sis-mongo-a sis-mongo-b sis-mongos"
DEMO_STAFF_EMAIL=${DEMO_STAFF_EMAIL:-staff@example.test}
DEMO_STAFF_PASSWORD=${DEMO_STAFF_PASSWORD:-sis-demo-2026}
DB_URL=${DATABASE_URL:-postgresql+psycopg://sis:sis_dev_only@127.0.0.1:5432/sis}

WITH_TESTS=0 VERIFY=0 NO_INSTALL=0

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
ok()   { printf '    \033[32m%s\033[0m\n' "$*"; }
warn() { printf '    \033[33m%s\033[0m\n' "$*"; }
die()  { printf '\n\033[31m%s\033[0m\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }
port_open() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

for arg in "$@"; do
  case "$arg" in
    --with-tests) WITH_TESTS=1 ;;
    --verify)     VERIFY=1 ;;
    --no-install) NO_INSTALL=1 ;;
    --stop)       exec "$ROOT/stop.sh" ;;
    -h|--help)    sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *)            die "unknown option: $arg (try --help)" ;;
  esac
done

say "Preflight"
[ -d "$APP" ] || die "expected the app in $APP"

# --- container runtime (cannot be installed without root) -------------------
if ! have podman; then
  warn "podman is required: the stack script drives containers, and this machine has none."
  printf '    install it, then re-run:\n'
  printf '      Debian/Ubuntu : sudo apt install -y podman\n'
  printf '      Fedora        : sudo dnf install -y podman\n'
  printf '      Arch          : sudo pacman -S podman\n'
  printf '      macOS         : brew install podman && podman machine init && podman machine start\n'
  die "podman missing - nothing was started."
fi
podman info >/dev/null 2>&1 || die "podman is installed but not usable. On rootless setups run 'podman system migrate' and re-run."
ok "podman $(podman --version | awk '{print $3}')"

# --- uv + python (installable in user space) --------------------------------
if ! have uv; then
  if [ "$NO_INSTALL" = 1 ]; then
    die "uv missing and --no-install was given (install: curl -LsSf https://astral.sh/uv/install.sh | sh)"
  fi
  say "Installing uv (user space, no sudo)"
  curl -LsSf https://astral.sh/uv/install.sh | sh >/dev/null 2>&1 || die "uv install failed"
  export PATH="$HOME/.local/bin:$PATH"
  have uv || die "uv installed but not on PATH; add \$HOME/.local/bin to PATH"
  ok "uv $(uv --version | awk '{print $2}') installed"
else
  ok "uv $(uv --version | awk '{print $2}')"
fi

# --- ports -------------------------------------------------------------------
for port in $STORE_PORTS $API_PORT; do
  if port_open "$port"; then
    if [ -f "$RUN/api.pid" ] && [ "$port" = "$API_PORT" ] && kill -0 "$(cat "$RUN/api.pid")" 2>/dev/null; then
      ok "port $port held by this project's API (will be reused)"
    elif podman container exists sis-postgres 2>/dev/null && [ "$port" != "$API_PORT" ]; then
      ok "port $port already held by a sis-* container (stack is partly up)"
    else
      warn "port $port is already in use by something that is not part of this project"
      have ss && ss -ltnp 2>/dev/null | grep -E ":$port\b" | sed 's/^/      /' || true
      die "free port $port first (or stop the other process); nothing was changed."
    fi
  fi
done

# --- env file (gitignored, generated once) -----------------------------------
if [ ! -f "$APP/.env" ]; then
  secret=$( (head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n') )
  cat > "$APP/.env" <<EOF
# Generated by run.sh. Local development only - never commit this file.
DATABASE_URL=$DB_URL
SIS_ENV=development
SIS_TOKEN_SECRET=$secret
SIS_REDIS_URL=redis://127.0.0.1:6379/0
SIS_MONGO_URI=mongodb://127.0.0.1:27017
SIS_MONGO_DB=sis
SIS_RATE_LIMIT_ENABLED=true
SIS_RATE_LIMIT_CAPACITY=120
SIS_RATE_LIMIT_REFILL_PER_SECOND=10
SIS_CACHE_TTL_SECONDS=20
EOF
  chmod 600 "$APP/.env"
  ok "created sis-app/.env with a fresh token secret"
else
  ok "sis-app/.env present"
fi

cd "$APP"
mkdir -p "$RUN"

say "Python dependencies (uv sync)"
if [ "$WITH_TESTS" = 1 ]; then uv sync --extra test >/dev/null 2>&1; else uv sync >/dev/null 2>&1; fi
ok "environment ready at sis-app/.venv"

say "Starting the state stores (PostgreSQL, Redis, MongoDB sharded cluster)"
bash "$APP/scripts/start_stack.sh"

if [ "$WITH_TESTS" = 1 ]; then
  say "Test suite (this drops and recreates tables - it runs before seeding for that reason)"
  uv run --extra test pytest -q
  ok "tests passed"
fi

say "Seeding the demo data"
uv run python -m scripts.generate_dataset --students 1000 --courses 100 --offerings-per-course 2 \
  | tail -3 | sed 's/^/    /'
uv run python -m scripts.seed_demo | sed 's/^/    /'
uv run python -m scripts.create_staff --email "$DEMO_STAFF_EMAIL" --student-number STAFF001 \
  --name "Demo Staff" --password "$DEMO_STAFF_PASSWORD" >/dev/null
ok "staff account ready: $DEMO_STAFF_EMAIL"

say "Starting the API"
if [ -f "$RUN/api.pid" ]; then
  kill "$(cat "$RUN/api.pid")" 2>/dev/null || true
  sleep 1
fi
nohup "$APP/.venv/bin/uvicorn" app.main:app --host "$API_HOST" --port "$API_PORT" \
  > "$RUN/api.log" 2>&1 &
echo $! > "$RUN/api.pid"

ready=0
for _ in $(seq 60); do
  if curl -fsS "http://$API_HOST:$API_PORT/health" >/dev/null 2>&1; then ready=1; break; fi
  kill -0 "$(cat "$RUN/api.pid")" 2>/dev/null || break
  sleep 1
done
if [ "$ready" != 1 ]; then
  warn "the API did not answer /health within 60s. Last log lines:"
  tail -20 "$RUN/api.log" | sed 's/^/      /'
  die "startup failed - run ./stop.sh, then inspect sis-app/.run/api.log"
fi
ok "API pid $(cat "$RUN/api.pid")"

say "Health"
curl -fsS "http://$API_HOST:$API_PORT/health" | python3 -m json.tool 2>/dev/null | sed 's/^/    /' || true

if [ "$VERIFY" = 1 ]; then
  say "Verifying the real stores (measured, not asserted)"
  uv run python scripts/verify_stack.py
fi

printf '\n\033[1;32mEverything is up.\033[0m\n'
printf '  dashboard   http://%s:%s/\n' "$API_HOST" "$API_PORT"
printf '  API docs    http://%s:%s/docs\n' "$API_HOST" "$API_PORT"
printf '  health      http://%s:%s/health\n' "$API_HOST" "$API_PORT"
printf '  staff login %s / %s\n' "$DEMO_STAFF_EMAIL" "$DEMO_STAFF_PASSWORD"
printf '  stop        ./stop.sh\n\n'
